-- Criação da tabela de Categorias
CREATE TABLE IF NOT EXISTS categoria (
    id_catego_cat BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nm_catego_cat VARCHAR(255) NOT NULL,
    ds_catego_cat VARCHAR(255),
    ds_icone_cat VARCHAR(255),
    fl_ativos_cat BOOLEAN DEFAULT TRUE,
    dt_criaca_cat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    dt_altera_cat TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- Tabela de Autores
CREATE TABLE IF NOT EXISTS autor (
    id_autor_aut BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nm_autor_aut VARCHAR(255) NOT NULL,
    ds_autor_aut VARCHAR(255),
    dt_criaca_aut TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    dt_altera_aut TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- Tabela de Autores
CREATE TABLE IF NOT EXISTS diretor (
    id_direto_dir BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nm_direto_dir VARCHAR(255) NOT NULL,
    ds_direto_dir VARCHAR(255),
    dt_criaca_dir TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    dt_altera_dir TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- Tabela para armazenar as mensagens de contato
CREATE TABLE IF NOT EXISTS contato (
    id_contat_con BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nm_contat_con VARCHAR(100) NOT NULL,
    ds_email_con VARCHAR(100) NOT NULL,
    ds_telddd_con VARCHAR(2),
    ds_telnum_con VARCHAR(15),
    mm_mensag_con TEXT NOT NULL,
    dt_envio_con TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Criação da tabela de Produtos
CREATE TABLE IF NOT EXISTS produto (
    id_produt_pro BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nm_produt_pro VARCHAR(255) NOT NULL,
    ds_produt_pro TEXT,
    id_catego_cat BIGINT NOT NULL,
    id_autor_aut BIGINT NOT NULL,
    id_direto_dir BIGINT NOT NULL,
    vl_preco_pro DECIMAL(10,2) NOT NULL,
    mm_foto_pro TEXT,
    fl_ativos_pro BOOLEAN DEFAULT TRUE,
    dt_lancam_pro TIMESTAMP NOT NULL,
    dt_cadast_pro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    dt_altera_pro TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (id_catego_cat) REFERENCES categoria(id_catego_cat),
    FOREIGN KEY (id_autor_aut) REFERENCES autor(id_autor_aut),
    FOREIGN KEY (id_direto_dir) REFERENCES diretor(id_direto_dir)
);


CREATE TABLE IF NOT EXISTS usuario (
    id_usuari_usu UUID DEFAULT RANDOM_UUID() PRIMARY KEY,
    nm_usuari_usu VARCHAR(255) NOT NULL,
    ds_email_usu VARCHAR(255) NOT NULL UNIQUE,
    ds_senha_usu VARCHAR(255) NOT NULL,
    fl_ativo_usu BOOLEAN DEFAULT TRUE NOT NULL,
    dt_criaca_usu TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    dt_atuali_usu TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS perfil (
    id_perfil_per BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nm_perfil_per VARCHAR(100) NOT NULL UNIQUE,
    fl_ativo_per BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE IF NOT EXISTS usuario_perfil (
    id_usuper_upe BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuari_usu UUID NOT NULL,
    id_perfil_per BIGINT NOT NULL,
    FOREIGN KEY (id_usuari_usu) REFERENCES usuario(id_usuari_usu),
    FOREIGN KEY (id_perfil_per) REFERENCES Perfil(id_perfil_per)
);
-- Índices para melhorar performance de buscas
CREATE INDEX IF NOT EXISTS idx_produto_nome ON produto(nm_produt_pro);
CREATE INDEX IF NOT EXISTS idx_produto_categoria ON produto(id_catego_cat);
CREATE INDEX IF NOT EXISTS idx_produto_autor ON produto(id_autor_aut);